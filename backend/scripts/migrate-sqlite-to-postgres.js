#!/usr/bin/env node
const path = require('path');
const Database = require('better-sqlite3');
const { Client } = require('pg');
const { DB_PATH } = require('../src/config');

const args = process.argv.slice(2);

function readArg(name, fallback = '') {
  const exact = args.find((arg) => arg.startsWith(`${name}=`));
  if (exact) {
    return exact.slice(name.length + 1);
  }
  const index = args.indexOf(name);
  if (index >= 0 && args[index + 1]) {
    return args[index + 1];
  }
  return fallback;
}

const sqlitePath = path.resolve(readArg('--sqlite-path', DB_PATH));
const connectionString = readArg('--postgres-url', process.env.DATABASE_URL || '');
const targetSchema = readArg('--schema', 'public');

if (!connectionString) {
  throw new Error('PostgreSQL bağlantısı gerekli. --postgres-url veya DATABASE_URL verin.');
}

function quoteIdent(value) {
  return `"${String(value).replace(/"/g, '""')}"`;
}

function mapSqliteTypeToPostgres(type) {
  const normalized = String(type || '').toUpperCase();
  if (normalized.includes('INT')) return 'BIGINT';
  if (normalized.includes('CHAR') || normalized.includes('CLOB') || normalized.includes('TEXT')) return 'TEXT';
  if (normalized.includes('BLOB')) return 'BYTEA';
  if (normalized.includes('REAL') || normalized.includes('FLOA') || normalized.includes('DOUB')) return 'DOUBLE PRECISION';
  if (normalized.includes('NUMERIC') || normalized.includes('DECIMAL')) return 'NUMERIC';
  if (normalized.includes('DATE') || normalized.includes('TIME')) return 'TIMESTAMP';
  return 'TEXT';
}

function normalizeDefaultValue(value) {
  if (value === null || value === undefined) return null;
  const raw = String(value).trim();
  if (!raw) return null;
  if (/^CURRENT_TIMESTAMP$/i.test(raw)) return 'CURRENT_TIMESTAMP';
  return raw;
}

async function main() {
  const sqlite = new Database(sqlitePath, { readonly: true, fileMustExist: true });
  const client = new Client({ connectionString });
  await client.connect();

  try {
    await client.query('BEGIN');
    await client.query(`CREATE SCHEMA IF NOT EXISTS ${quoteIdent(targetSchema)}`);
    await client.query(`SET search_path TO ${quoteIdent(targetSchema)}`);

    const tables = sqlite
      .prepare("SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
      .all();

    const deferredForeignKeys = [];

    for (const table of tables) {
      const tableName = table.name;
      const columns = sqlite.prepare(`PRAGMA table_info(${quoteIdent(tableName)})`).all();
      const foreignKeys = sqlite.prepare(`PRAGMA foreign_key_list(${quoteIdent(tableName)})`).all();

      const pkColumns = columns.filter((column) => column.pk > 0).sort((a, b) => a.pk - b.pk);
      const hasSinglePk = pkColumns.length === 1;

      const columnSql = columns.map((column) => {
        const name = quoteIdent(column.name);
        const sqliteType = String(column.type || '').toUpperCase();
        const isAutoincrement = hasSinglePk
          && column.pk === 1
          && sqliteType.includes('INT')
          && String(table.sql || '').toUpperCase().includes(`${String(column.name).toUpperCase()} INTEGER PRIMARY KEY AUTOINCREMENT`);

        const typeSql = isAutoincrement ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY' : mapSqliteTypeToPostgres(column.type);
        const notNullSql = column.notnull ? ' NOT NULL' : '';
        const defaultSql = normalizeDefaultValue(column.dflt_value);
        const defaultClause = defaultSql ? ` DEFAULT ${defaultSql}` : '';

        return `${name} ${typeSql}${notNullSql}${defaultClause}`;
      });

      const constraints = [];
      if (pkColumns.length > 0) {
        constraints.push(`PRIMARY KEY (${pkColumns.map((column) => quoteIdent(column.name)).join(', ')})`);
      }

      const createSql = `CREATE TABLE ${quoteIdent(tableName)} (\n  ${columnSql.concat(constraints).join(',\n  ')}\n)`;
      await client.query(`DROP TABLE IF EXISTS ${quoteIdent(tableName)} CASCADE`);
      await client.query(createSql);

      const rows = sqlite.prepare(`SELECT * FROM ${quoteIdent(tableName)}`).all();
      if (rows.length > 0) {
        const colNames = columns.map((col) => col.name);
        const insertSql = `INSERT INTO ${quoteIdent(tableName)} (${colNames.map(quoteIdent).join(', ')}) VALUES (${colNames.map((_, i) => `$${i + 1}`).join(', ')})`;
        for (const row of rows) {
          const values = colNames.map((name) => row[name]);
          await client.query(insertSql, values);
        }
      }

      const idColumn = columns.find((column) => column.name === 'id' && column.pk > 0);
      if (idColumn) {
        await client.query(
          `SELECT setval(
             pg_get_serial_sequence($1, 'id'),
             GREATEST(COALESCE((SELECT MAX(id) FROM ${quoteIdent(tableName)}), 0), 1),
             (SELECT COUNT(*) > 0 FROM ${quoteIdent(tableName)})
           )`,
          [tableName]
        );
      }

      if (foreignKeys.length > 0) {
        deferredForeignKeys.push({ tableName, foreignKeys });
      }

      const indexes = sqlite.prepare(`PRAGMA index_list(${quoteIdent(tableName)})`).all();
      for (const indexInfo of indexes) {
        if (indexInfo.origin === 'pk') {
          continue;
        }
        const indexName = indexInfo.name;
        const indexColumns = sqlite.prepare(`PRAGMA index_info(${quoteIdent(indexName)})`).all();
        if (!indexColumns.length) {
          continue;
        }
        const uniqueClause = indexInfo.unique ? 'UNIQUE ' : '';
        const colsSql = indexColumns.map((item) => quoteIdent(item.name)).join(', ');
        await client.query(`DROP INDEX IF EXISTS ${quoteIdent(indexName)}`);
        await client.query(`CREATE ${uniqueClause}INDEX ${quoteIdent(indexName)} ON ${quoteIdent(tableName)} (${colsSql})`);
      }
    }

    for (const fkTable of deferredForeignKeys) {
      const grouped = new Map();
      for (const fk of fkTable.foreignKeys) {
        if (!grouped.has(fk.id)) {
          grouped.set(fk.id, []);
        }
        grouped.get(fk.id).push(fk);
      }

      for (const [fkId, entries] of grouped.entries()) {
        const sorted = entries.sort((a, b) => a.seq - b.seq);
        const fromColumns = sorted.map((entry) => quoteIdent(entry.from)).join(', ');
        const toColumns = sorted.map((entry) => quoteIdent(entry.to)).join(', ');
        const targetTable = quoteIdent(sorted[0].table);
        const onDelete = sorted[0].on_delete && sorted[0].on_delete !== 'NO ACTION' ? ` ON DELETE ${sorted[0].on_delete}` : '';
        const onUpdate = sorted[0].on_update && sorted[0].on_update !== 'NO ACTION' ? ` ON UPDATE ${sorted[0].on_update}` : '';
        const constraintName = quoteIdent(`fk_${fkTable.tableName}_${fkId}`);
        const sql = `ALTER TABLE ${quoteIdent(fkTable.tableName)} ADD CONSTRAINT ${constraintName} FOREIGN KEY (${fromColumns}) REFERENCES ${targetTable} (${toColumns})${onDelete}${onUpdate}`;
        await client.query(sql);
      }
    }

    await client.query('COMMIT');
    console.log(`SQLite -> PostgreSQL migration tamamlandı. Kaynak: ${sqlitePath}, schema: ${targetSchema}`);
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    sqlite.close();
    await client.end();
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
