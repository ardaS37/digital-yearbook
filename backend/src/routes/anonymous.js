const express = require('express');
const rateLimit = require('express-rate-limit');
const { db } = require('../db');
const { requireLogin } = require('../middleware/auth');
const { isFeatureEnabled } = require('../utils/features');
const { verifyCsrf } = require('../middleware/csrf');
const { stripHtml } = require('../utils/sanitize');
const { writeAuditLog } = require('../utils/auditLog');
const { canReviewContent, createApprovalRequest, isContentApprovalEnabled } = require('../utils/contentApproval');
const { validateContentText } = require('../utils/contentModeration');

const router = express.Router();
const MAX_ANONYMOUS_MESSAGE_LENGTH = 600;

const ALLOWED_NOTE_COLORS = [
  '#fde68a', // sıcak sarı
  '#bbf7d0', // nane yeşili
  '#fecdd3', // gül pembesi
  '#bae6fd', // gökyüzü mavisi
  '#fed7aa', // şeftali
  '#ddd6fe', // lavanta
  '#99f6e4', // turkuaz
  '#fef9c3', // krem
];

db.exec(
  process.env.DATABASE_URL
    ? `CREATE TABLE IF NOT EXISTS anonymous_board_posts (
        id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        author_user_id BIGINT,
        approval_request_id BIGINT,
        body TEXT NOT NULL,
        note_color TEXT,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (author_user_id) REFERENCES users(id) ON DELETE SET NULL
      )`
    : `CREATE TABLE IF NOT EXISTS anonymous_board_posts (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        author_user_id INTEGER,
        approval_request_id INTEGER,
        body TEXT NOT NULL,
        note_color TEXT,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (author_user_id) REFERENCES users(id) ON DELETE SET NULL
      )`
);
try {
  db.exec('ALTER TABLE anonymous_board_posts ADD COLUMN approval_request_id INTEGER');
} catch (error) {
  if (!String(error.message || '').match(/duplicate column|already exists/i)) {
    throw error;
  }
}
try {
  db.exec('ALTER TABLE anonymous_board_posts ADD COLUMN note_color TEXT');
} catch (error) {
  if (!String(error.message || '').match(/duplicate column|already exists/i)) {
    throw error;
  }
}
db.exec('CREATE INDEX IF NOT EXISTS idx_anonymous_board_posts_created_at ON anonymous_board_posts(created_at)');

function parsePayloadJson(value) {
  try {
    return JSON.parse(value || '{}');
  } catch (error) {
    return {};
  }
}

function applyApprovalAuthors(posts) {
  const approvals = db
    .prepare(
      `SELECT r.id, r.actor_user_id, r.payload_json, actor.name AS actor_name, actor.role AS actor_role
       FROM content_approval_requests r
       JOIN users actor ON actor.id = r.actor_user_id
       WHERE r.item_type = 'anonymous_board_post' AND r.status = 'approved'
       ORDER BY r.reviewed_at DESC, r.created_at DESC`
    )
    .all()
    .map((item) => ({ ...item, payload: parsePayloadJson(item.payload_json) }));
  return posts.map((post) => {
    const approval = approvals.find((item) => {
      if (post.approval_request_id && Number(item.id) === Number(post.approval_request_id)) return true;
      return String(item.payload.body || '') === String(post.body || '') && item.actor_role !== 'admin';
    });
    return approval
      ? { ...post, author_user_id: approval.actor_user_id, author_name: approval.actor_name }
      : post;
  });
}

const anonymousPostLimiter = rateLimit({
  windowMs: 10 * 60 * 1000,
  max: 20,
  standardHeaders: true,
  legacyHeaders: false,
  message: 'Çok sık mantar pano notu gönderildi. Lütfen biraz sonra tekrar deneyin.'
});

router.get('/anonymous-board', requireLogin, (req, res) => {
  if (!isFeatureEnabled(req.featureFlags || {}, 'anonymous_board')) {
    req.flash('error', 'Mantar pano şu anda kapalı.');
    return res.redirect('/');
  }
  const canModerateBoard = canReviewContent(req.currentUser);
  const posts = db
    .prepare(
      `SELECT p.id, p.body, p.note_color, p.created_at, p.author_user_id, p.approval_request_id, author.name AS author_name
       FROM anonymous_board_posts p
       LEFT JOIN users author ON author.id = p.author_user_id
       ORDER BY p.created_at DESC
       LIMIT 100`
    )
    .all();
  const displayPosts = applyApprovalAuthors(posts);

  return res.render('anonymous-board', {
    title: 'Mantar Pano',
    posts: displayPosts,
    canModerateBoard,
    currentUserId: req.currentUser.id,
    maxLength: MAX_ANONYMOUS_MESSAGE_LENGTH,
    contentApprovalEnabled: isContentApprovalEnabled(db),
    allowedNoteColors: ALLOWED_NOTE_COLORS
  });
});

router.post('/anonymous-board', requireLogin, anonymousPostLimiter, verifyCsrf, (req, res) => {
  if (!isFeatureEnabled(req.featureFlags || {}, 'anonymous_board')) {
    req.flash('error', 'Mantar pano şu anda kapalı.');
    return res.redirect('/');
  }
  if (req.currentUser.role === 'guest') {
    req.flash('error', 'Misafir profili mantar panoya not yazamaz.');
    return res.redirect('/anonymous-board');
  }

  const body = stripHtml(req.body.body || '').slice(0, MAX_ANONYMOUS_MESSAGE_LENGTH);
  const rawColor = stripHtml(req.body.note_color || '').trim();
  const noteColor = ALLOWED_NOTE_COLORS.includes(rawColor) ? rawColor : ALLOWED_NOTE_COLORS[0];
  if (!body) {
    req.flash('error', 'Mantar pano notu boş olamaz.');
    return res.redirect('/anonymous-board');
  }

  const moderation = validateContentText(db, body, { minLength: 5 });
  if (!moderation.ok) {
    req.flash('error', moderation.message);
    return res.redirect('/anonymous-board');
  }

  if (isContentApprovalEnabled(db) && req.currentUser.role !== 'admin') {
    createApprovalRequest(db, {
      itemType: 'anonymous_board_post',
      actorUserId: req.currentUser.id,
      targetUserId: null,
      payload: { body, note_color: noteColor }
    });
    writeAuditLog({
      actorUserId: req.currentUser.id,
      action: 'content_approval_request_create',
      targetType: 'anonymous_board_post',
      targetId: null,
    details: { itemType: 'anonymous_board_post', authorUserId: req.currentUser.id, authorName: req.currentUser.name, messageLength: body.length }
    });
    req.flash('success', 'Mantar pano notu onaya gönderildi. Onaylanınca panoda yayınlanacak.');
    return res.redirect('/anonymous-board');
  }

  const result = db
    .prepare('INSERT INTO anonymous_board_posts (author_user_id, body, note_color) VALUES (?, ?, ?)')
    .run(req.currentUser.id, body, noteColor);
  writeAuditLog({
    actorUserId: req.currentUser.id,
    action: 'anonymous_board_post_create',
    targetType: 'anonymous_board_post',
    targetId: Number(result.lastInsertRowid || 0) || null,
    details: { authorUserId: req.currentUser.id, authorName: req.currentUser.name, messageLength: body.length }
  });
  req.flash('success', 'Mantar pano notu yayınlandı.');
  return res.redirect('/anonymous-board');
});

router.post('/anonymous-board/:id/delete', requireLogin, verifyCsrf, (req, res) => {
  const id = Number(req.params.id);
  if (!Number.isInteger(id) || id <= 0) {
    req.flash('error', 'Geçersiz mantar pano notu.');
    return res.redirect('/anonymous-board');
  }
  const post = db
    .prepare(
      `SELECT p.id, p.author_user_id, p.body, author.name AS author_name
       FROM anonymous_board_posts p
       LEFT JOIN users author ON author.id = p.author_user_id
       WHERE p.id = ?`
    )
    .get(id);
  if (!post) {
    req.flash('error', 'Mantar pano notu bulunamadı.');
    return res.redirect('/anonymous-board');
  }
  const canDelete = canReviewContent(req.currentUser) || Number(post.author_user_id || 0) === Number(req.currentUser.id);
  if (!canDelete) {
    req.flash('error', 'Sadece kendi mantar pano notunuzu silebilirsiniz.');
    return res.redirect('/anonymous-board');
  }
  db.prepare('DELETE FROM anonymous_board_posts WHERE id = ?').run(id);
  writeAuditLog({
    actorUserId: req.currentUser.id,
    action: 'anonymous_board_post_delete',
    targetType: 'anonymous_board_post',
    targetId: id,
    details: { authorUserId: post.author_user_id || null, authorName: post.author_name || null, bodyPreview: String(post.body || '').slice(0, 120) }
  });
  req.flash('success', 'Mantar pano notu silindi.');
  return res.redirect('/anonymous-board');
});

module.exports = router;
